#!/usr/bin/env python3
"""source/chip_tree.json + lockeys.json + facts.json  ->  build/scripts/AshCacheChipData.reds

The Splinter perk tree (D115). The data half only: which perks exist, what they
cost, which fact records a purchase, which status effect carries the bonus, and
which LocKey names each one. The hand-written half - drawing and buying - is
source/scripts/AshCacheChipTree.reds, which reads nothing but this table.

Every table is a set of parallel arrays indexed by perk (or by point source), so the
.reds side never parses anything and a typo here is a build error, not a silent
zero at runtime. gen_tweak.py emits the matching BaseStatusEffect records from the
same file, so the TweakDBID written here and the record TweakXL creates cannot
drift apart.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "scripts" / "AshCacheChipData.reds"

# UI strings the tree draws that are not perk/branch names. Listed here, not in
# chip_tree.json, because the .reds code names them - adding one is a code change.
UI_STRINGS = ["chip_tree_name", "chip_tree_tagline", "chip_points", "chip_reset",
              "chip_dormant", "chip_burned", "chip_partial", "chip_locked_prev",
              "chip_locked_full", "chip_locked_points", "chip_owned", "chip_buy_hint",
              "chip_unlocked_msg", "chip_frag_msg"]


def effect_id(perk):
    return f"BaseStatusEffect.ashcache_chip_{perk['id']}"


def bought_fact(perk):
    return f"ashcache_chip_{perk['id']}"


def load():
    src = ROOT / "source"
    tree = json.loads((src / "chip_tree.json").read_text(encoding="utf-8"))
    lockeys = json.loads((src / "lockeys.json").read_text(encoding="utf-8"))
    lockeys.pop("_comment", None)
    return tree, lockeys


def check(tree, lockeys):
    errs = []
    facts = json.loads((ROOT / "source" / "facts.json").read_text(encoding="utf-8"))
    declared = {k for g in facts.values() if isinstance(g, dict) for k in g if not k.startswith("_")}

    def need_key(sid, where):
        if sid not in lockeys:
            errs.append(f"{where}: string id {sid!r} has no LocKey (strings.json + alloc_lockeys.py)")

    def need_fact(f, where):
        if f not in declared:
            errs.append(f"{where}: fact {f!r} is not declared in facts.json")

    for sid in UI_STRINGS:
        need_key(sid, "ui")
    branches = [b["id"] for b in tree["branches"]]
    for b in tree["branches"]:
        need_key(b["name"], f"branch {b['id']}")
    ids = set()
    for p in tree["perks"]:
        w = f"perk {p['id']}"
        if p["id"] in ids:
            errs.append(f"{w}: duplicate id")
        ids.add(p["id"])
        if p["branch"] not in branches:
            errs.append(f"{w}: unknown branch {p['branch']!r}")
        if p["tier"] > 1 and not any(q["branch"] == p["branch"] and q["tier"] == p["tier"] - 1
                                     for q in tree["perks"]):
            errs.append(f"{w}: tier {p['tier']} has no tier {p['tier'] - 1} to require")
        if not p["stats"]:
            errs.append(f"{w}: no stats - a perk that does nothing")
        need_key(p["name"], w)
        need_key(p["desc"], w)
        need_fact(bought_fact(p), w)
    for s in tree["points"]:
        need_fact(s["fact"], "points")
    for u in tree["unlock"]:
        need_fact(u["fact"], "unlock")
    point_facts = {s["fact"] for s in tree["points"]}
    for f in tree["fragments"]:
        w = f"fragment {f['fact']}"
        need_fact(f["fact"], w)
        if f["fact"] not in point_facts:
            errs.append(f"{w}: not a point source - collecting it would be worth nothing")
        if len(f["pos"]) != 3:
            errs.append(f"{w}: pos must be [x, y, z]")
    need_fact(tree["visible_fact"], "visible_fact")
    need_fact("ashcache_chip_notified", "ui")
    if errs:
        sys.exit("gen_chip: " + "\n  ".join([""] + errs))


def arr(items):
    return "[" + ", ".join(items) + "]"


def main():
    tree, lockeys = load()
    check(tree, lockeys)
    perks = tree["perks"]
    branch_ix = {b["id"]: i for i, b in enumerate(tree["branches"])}

    def fn(name, rtype, value):
        return f"  public static func {name}() -> {rtype} {{ return {value}; }}"

    lines = [
        "// GENERATED by tools/gen_chip.py from source/chip_tree.json - do not hand-edit.",
        "// The Splinter perk tree data (D115). Parallel arrays indexed by perk.",
        "",
        "module AshCacheChip",
        "",
        "public abstract class AshCacheChipData {",
        fn("PerkCount", "Int32", str(len(perks))),
        fn("PerkBranch", "array<Int32>", arr(str(branch_ix[p["branch"]]) for p in perks)),
        fn("PerkTier", "array<Int32>", arr(str(p["tier"]) for p in perks)),
        fn("PerkCost", "array<Int32>", arr(str(p["cost"]) for p in perks)),
        fn("PerkFact", "array<CName>", arr(f'n"{bought_fact(p)}"' for p in perks)),
        fn("PerkEffect", "array<TweakDBID>", arr(f't"{effect_id(p)}"' for p in perks)),
        fn("PerkName", "array<String>", arr(f'"LocKey#{lockeys[p["name"]]}"' for p in perks)),
        fn("PerkDesc", "array<String>", arr(f'"LocKey#{lockeys[p["desc"]]}"' for p in perks)),
        fn("BranchCount", "Int32", str(len(tree["branches"]))),
        fn("BranchName", "array<String>", arr(f'"LocKey#{lockeys[b["name"]]}"' for b in tree["branches"])),
        fn("TierCount", "Int32", str(max(p["tier"] for p in perks))),
        fn("FullTier", "Int32", str(tree["full_tier"])),
        fn("PointFacts", "array<CName>", arr(f'n"{s["fact"]}"' for s in tree["points"])),
        fn("PointValues", "array<Int32>", arr(str(s["points"]) for s in tree["points"])),
        fn("UnlockFacts", "array<CName>", arr(f'n"{u["fact"]}"' for u in tree["unlock"])),
        fn("UnlockLevels", "array<Int32>", arr(str(u["level"]) for u in tree["unlock"])),
        fn("VisibleFact", "CName", f'n"{tree["visible_fact"]}"'),
        fn("NotifiedFact", "CName", 'n"ashcache_chip_notified"'),
        fn("FragFacts", "array<CName>", arr(f'n"{f["fact"]}"' for f in tree["fragments"])),
        fn("FragPos", "array<Vector4>",
           arr(f"Vector4({x}, {y}, {z}, 1.0)" for x, y, z in (f["pos"] for f in tree["fragments"]))),
        fn("FragYaw", "array<Float>", arr(str(float(f["yaw"])) for f in tree["fragments"])),
        fn("FragRadius", "Float", str(float(tree["fragment_radius"]))),
        fn("FragZOffset", "Float", str(float(tree["fragment_z_offset"]))),
        fn("FragTemplate", "ResRef", 'r"' + tree["fragment_template"].replace("\\", "\\\\") + '"'),
    ]
    for sid in UI_STRINGS:
        camel = "".join(w.capitalize() for w in sid.split("_")[1:])
        lines.append(fn(f"S{camel}", "String", f'"LocKey#{lockeys[sid]}"'))
    lines += ["}", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"chip: {len(perks)} perk(s), {len(tree['points'])} point source(s), {len(tree['fragments'])} fragment(s) -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
