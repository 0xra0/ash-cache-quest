#!/usr/bin/env python3
"""Allocate stable subtitle string ids for every spoken line and choice option.

Scene subtitles do NOT use LocKeys. A line in a .scene carries a
scnlocLocstringId.ruid, and the text is looked up by that ruid in a
localizationPersistenceSubtitleEntries resource. Two independent namespaces:

    journal / UI text  ->  LocKey        ->  onscreens.json   (alloc_lockeys.py)
    spoken scene text  ->  locstring ruid ->  subtitles json   (this file)

The ruids are arbitrary. That is not an assumption: Undermine Quest Series ships
a choice option with ruid 9999999999900000003, a hand-picked number, and its own
subtitle file keys off exactly that. They only have to match between the .scene
and the subtitle resource. So, like LocKeys, they come from a reserved block and
are never renumbered - a shifted ruid silently repoints a line's text.

Reserved block for Ash Cache: 7731500000000000000-7731500000000000999.
The 77315 prefix is the same project marker as the LocKey block, so an id found
in a crash log is traceable to this mod. It sits clear of vanilla (~1-3e18) and
of Undermine (9.99e18), and stays below 2^63 in case any consumer reads it signed.
"""
import json
import pathlib
import sys

BLOCK_START = 7731500000000000000
BLOCK_END = 7731500000000000999

ROOT = pathlib.Path(__file__).resolve().parent.parent
ALLOC = ROOT / "source" / "subtitle_ids.json"


def spoken_ids(scene):
    """Every id in one scene source that needs a subtitle ruid, in file order."""
    out = []
    for node in scene.get("nodes", []):
        for line in node.get("lines", []):
            out.append(line["id"])
        for opt in node.get("options", []):
            out.append(opt["id"])
    return out


def collect():
    """(scene stem, line id) pairs across every source/scene_*.json."""
    pairs = []
    for path in sorted((ROOT / "source").glob("scene_*.json")):
        scene = json.loads(path.read_text(encoding="utf-8"))
        stem = path.stem[len("scene_"):]
        for lid in spoken_ids(scene):
            key = f"{stem}.{lid}"
            if key in [p for p, _ in pairs]:
                sys.exit(f"duplicate line id {lid!r} in {path.name}")
            pairs.append((key, path.name))
    return pairs


def main():
    pairs = collect()
    ids = [k for k, _ in pairs]

    alloc = {}
    if ALLOC.exists():
        alloc = json.loads(ALLOC.read_text(encoding="utf-8"))
        alloc.pop("_comment", None)

    used = {int(v) for v in alloc.values()}
    nxt = BLOCK_START
    added = []
    for key in ids:
        if key in alloc:
            continue
        while nxt in used:
            nxt += 1
        if nxt > BLOCK_END:
            sys.exit(f"subtitle id block {BLOCK_START}-{BLOCK_END} exhausted")
        # Stored as a string: these exceed 2^53 and would lose precision if any
        # consumer of this file parsed it as a JSON number (jq does exactly that).
        alloc[key] = str(nxt)
        used.add(nxt)
        added.append((key, nxt))
        nxt += 1

    orphans = [k for k in alloc if k not in ids]

    out = {"_comment": f"Generated by tools/alloc_subtitle_ids.py. "
                       f"Block {BLOCK_START}-{BLOCK_END}. "
                       "Append-only - never renumber an existing entry."}
    out.update({k: alloc[k] for k in sorted(alloc, key=lambda x: int(alloc[x]))})
    ALLOC.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"allocated {len(added)} new, {len(alloc)} total subtitle ids")
    for key, n in added:
        print(f"  +{n}  {key}")
    if orphans:
        print(f"WARNING: {len(orphans)} allocated ids no longer in any scene "
              f"(kept, never reuse the number): {orphans}")


if __name__ == "__main__":
    main()
