#!/usr/bin/env python3
"""source/characters.json + source/items.json  ->  build/tweaks/ash_cache.yaml

The one resource in this mod that is NOT packed into the .archive. TweakXL reads
loose YAML from r6/tweaks/, so this file is deployed alongside the archive rather
than inside it, and the .xl manifest says nothing about it.

The record shape is Hot Fuzz's, which is the whole mechanism in two lines:

    Character.judy_max:
      $base: Character.Judy
      entityTemplatePath: base\\quest\\secondary_characters\\judy_max.ent

$base inherits everything - entity template, appearance list, faction, behaviour -
and each key below it overrides one field. Ash Cache overrides nothing structural:
Mara inherits a vanilla scene NPC wholesale and only gets her own name, because the
alternative is authoring an .ent, and a real one runs to 100 components and 128
resolved dependencies (measured on judy_max.ent). That is not a headless job.

displayName is written as LocKey#N. That is the numeric form, which is what the
installed tweaks use where they reference a real LocKey, and it keeps NPC names on
the same reserved-block discipline as every other string in the mod (rule 6).

ITEMS follow the same inherit-and-override rule, and both of their shapes were
settled by reading the VALUES of the vanilla records out of the game's own
tweakdb_ep1.bin rather than by copying a reference mod:

  kind 'item'   $base Items.q003_chip - the Flathead. Gen_Misc, ItemCategory
                General, isSingleInstance, tagged 'Quest', and objectActions
                containing neither Drop nor Disassemble. Its one inherited action
                is a Flathead-specific 'Crack', so objectActions is cleared.
  kind 'shard'  $base Items.mq006_body_shard - vanilla's own readable quest shard,
                which brings ItemType.Gen_Readable and the tag list
                [Readable, Shard, SkipActivityLog, HideInBackpackUI, HideAtVendor]
                with it. Its Read action is inherited too, so the child action
                overrides exactly one field: which journal entry it opens.

Where a reference mod and vanilla disagree, vanilla wins. Aldecaldos High Stakes
writes hackCategory: HackCategory.DeviceHack on its shard's read action; vanilla's
equivalent is HackCategory.NotAHack, which is what an item action should be. That
difference is inherited away entirely by using $base.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "tweaks" / "ash_cache.yaml"

HEADER = """# GENERATED by tools/gen_tweak.py from source/characters.json + items.json - do not hand-edit.
# Deploy to  r6/tweaks/ash_cache.yaml  (loose file, NOT inside the .archive).
"""


def lockey_ref(sid, lockeys):
    if sid not in lockeys:
        sys.exit(f"characters.json names string id {sid!r}, which has no LocKey - "
                 f"add it to source/strings.json and run tools/alloc_lockeys.py")
    return f"LocKey#{lockeys[sid]}"


# Vanilla records every generated item inherits from. Named here rather than in
# source/items.json because they are not a content choice - they are what "a quest
# object" and "a readable shard" mean in this game, read out of its own TweakDB.
SHARD_BASE = "Items.mq006_body_shard"
SHARD_ACTION_BASE = "Items.mq006_body_shard_inline0"


def item_records(item, lockeys):
    """One item -> the YAML block(s) that define it. A shard is two records."""
    name = f"Items.{item['record']}"
    body = [f"{name}:"]
    blocks = []

    if item["kind"] == "shard":
        action = f"{name}_inline0"
        body += [f"  $base: {SHARD_BASE}",
                 f"  displayName: {lockey_ref(item['displayName'], lockeys)}",
                 f"  localizedDescription: {lockey_ref(item['description'], lockeys)}",
                 f"  itemSecondaryAction: {action}"]
        os_ = item["onscreen"]
        blocks.append([f"{action}:",
                       f"  $base: {SHARD_ACTION_BASE}",
                       # The path into the journal's onscreens tree. gen_journal.py
                       # builds the matching folder/group/entry; if these two ever
                       # disagree the shard opens an empty reader, which is why
                       # validate.py checks the pair rather than trusting them.
                       f"  journalEntry: onscreens/{os_['group']}/{os_['entry']}"])
    else:
        body += [f"  $base: {item['base']}",
                 f"  displayName: {lockey_ref(item['displayName'], lockeys)}",
                 f"  localizedDescription: {lockey_ref(item['description'], lockeys)}"]
        if not item.get("keep_actions"):
            # q003_chip's only action is the Flathead's own 'Crack', complete
            # with an effector. Inheriting it would put a Crack option on the
            # splinter; clearing it leaves a quest object that is carried and
            # nothing else - still undroppable, because Drop was never in the
            # list to begin with.
            body.append("  objectActions: []")
        # D186: a weapon with its own numbers. 'tweak' is raw YAML lines for the
        # record. 'stats' go in a StatModifierGroup of their own (D187): an
        # '!append' on the new record's statModifiers REPLACED the 150 inherited
        # Base_Weapon modifiers (read live), leaving damage and magazine at 0 and
        # the gun hidden from the inventory. The record lists the group in its
        # statModifierGroups (in 'tweak'); statModifiers stays inherited.
        body += item.get("tweak", [])
        # D189: tier is the record's 'quality' field (a Quality record, not a
        # stat modifier - in statModifiers it did nothing). Iconics inherit
        # Quality.Random, which GiveItem rolls as Tier 1; read live: Legendary
        # here gives Quality 4, damage 73 vs 33.
        if item.get("quality"):
            body.append(f"  quality: {item['quality']}")
        if item.get("stats"):
            group = [f"{name}_stats:",
                     "  $type: StatModifierGroup",
                     "  drawBasedOnStatType: false",
                     "  optimiseCombinedModifiers: false",
                     "  saveBasedOnStatType: false",
                     "  statModsLimit: -1",
                     "  statModifiers:"]
            if "IconicWeapon" in " ".join(item.get("tweak", [])):
                group.append("    - Quality.IconicItem")
            for stat, mtype, value in item["stats"]:
                group += ["    - $type: ConstantStatModifier",
                          f"      statType: BaseStats.{stat}",
                          f"      modifierType: {mtype}",
                          f"      value: {float(value)}"]
            blocks.append(group)
    return [body] + blocks


def main():
    src = ROOT / "source"
    chars = json.loads((src / "characters.json").read_text(encoding="utf-8"))
    items = json.loads((src / "items.json").read_text(encoding="utf-8"))
    lockeys = json.loads((src / "lockeys.json").read_text(encoding="utf-8"))
    lockeys.pop("_comment", None)

    lines = [HEADER]
    for c in chars["characters"]:
        # Every override is one line; order is fixed so the diff of a regenerated
        # file shows only what actually changed in the source.
        body = [f"  $base: {c['base']}"]
        if "displayName" in c:
            body.append(f"  displayName: {lockey_ref(c['displayName'], lockeys)}")
        if "fullDisplayName" in c:
            body.append(f"  fullDisplayName: {lockey_ref(c['fullDisplayName'], lockeys)}")
        # A quest NPC you walk up to and talk to needs a nameplate; the vanilla
        # background traveller Mara inherits from does not have one on by default.
        # A nameplate is drawn over a head. A voice (D126) has neither, so writing
        # it here would be an override of a field that nothing will ever read.
        if not c.get("voice"):
            body.append("  uiNameplate: UINameplate.Always")

        lines.append(f"Character.{c['record']}:")
        lines.extend(body)
        lines.append("")

    # Combat NPCs placed by a worldPopulationSpawnerNode. Only the attitude group
    # differs from the vanilla base; see characters.json _enemies.
    for e in chars.get("enemies", []):
        lines.append(f"Character.{e['record']}:")
        lines.append(f"  $base: {e['base']}")
        lines.append(f"  baseAttitudeGroup: {e['attitude']}")
        lines.append("")

    n_rec = 0
    for item in items["items"]:
        for block in item_records(item, lockeys):
            lines.extend(block)
            lines.append("")
            n_rec += 1

    # The Splinter perk tree (D115): one status effect per perk carrying its stats.
    # $type StatusEffect with no uiData, so it puts no icon on the HUD - the shape
    # the installed MonowirePerkTree ships. savable: false because the tree
    # re-applies every bought perk from its fact on load; a savable effect would be
    # applied a second time on top of the saved one.
    chip = json.loads((src / "chip_tree.json").read_text(encoding="utf-8"))
    for p in chip["perks"]:
        lines += [f"BaseStatusEffect.ashcache_chip_{p['id']}:",
                  "  $type: StatusEffect",
                  "  statusEffectType: BaseStatusEffectTypes.Misc",
                  "  duration: BaseStats.InfiniteDuration",
                  "  savable: false",
                  "  isAffectedByTimeDilationNPC: false",
                  "  isAffectedByTimeDilationPlayer: false",
                  "  packages:",
                  "    - $type: GameplayLogicPackage",
                  "      stats:"]
        for stat, mtype, value in p["stats"]:
            lines += ["        - $type: ConstantStatModifier",
                      f"          statType: BaseStats.{stat}",
                      f"          modifierType: {mtype}",
                      f"          value: {float(value)}"]
        lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"tweaks: {len(chars['characters'])} character record(s), "
          f"{len(items['items'])} item(s) in {n_rec} record(s), "
          f"{len(chip['perks'])} chip perk effect(s) "
          f"-> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
