        "  let des = GameInstance.GetDynamicEntitySystem();",
        "  return IsDefined(des) && des.IsReady();",
        "}",
        "",
        "// Without Codeware there is nothing to wait for, and returning false here would",
        "// reschedule the retry forever. The props are simply not drawn.",
        "@if(!ModuleExists(\"Codeware\"))",
