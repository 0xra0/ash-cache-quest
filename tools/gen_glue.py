def main():
    src = ROOT / "source"
    glue = json.loads((src / "glue.json").read_text(encoding="utf-8"))
    world = json.loads((src / "world.json").read_text(encoding="utf-8"))
    items = {i["id"]: i for i in
             json.loads((src / "items.json").read_text(encoding="utf-8"))["items"]}

    markers = marker_table(world)
    for a in glue["areas"]:
        if a["marker"] not in markers:
            sys.exit(f"glue.json area {a['fact']!r} names marker {a['marker']!r}, "
                     f"which world.json does not define")
    for s in glue["shards"]:
        it = items.get(s["item"])
        if it is None or it["kind"] != "shard":
            sys.exit(f"glue.json shard {s['fact']!r} names item {s['item']!r}, "
                     f"which items.json does not define as a shard")

    # Props. Every one of these is a silent failure in game if it is wrong: a prop
    # drawn at the wrong pose, a state that can never match, or two states both
    # claiming the same tag, which would make one despawn the other's entity.
    props = prop_table(world)
    facts = json.loads((src / "facts.json").read_text(encoding="utf-8"))
    declared = {k for g in facts.values() if isinstance(g, dict)
                for k in g if not k.startswith("_")}
    tags = set()
    for item in glue.get("props", []):
        w = f"glue.json prop {item['id']!r}"
        p = props.get(item["prop"])
        if p is None:
            sys.exit(f"{w} names prop {item['prop']!r}, which world.json does not define")
        if not p.get("disabled"):
            sys.exit(f"{w} draws world.json prop {item['prop']!r}, which is still a live "
                     f"sector node - the placed node and the spawned one would overlap. "
                     f"Mark it 'disabled' there, with a disabled_why.")
        if not item["watch"]:
            sys.exit(f"{w} watches no facts, so its look would never change")
        for f in item["watch"]:
            if f not in declared:
                sys.exit(f"{w} watches fact {f!r}, which facts.json does not declare")
        for st in item["states"]:
            if st["tag"] in tags:
                sys.exit(f"{w} state tag {st['tag']!r} is used twice - one state would "
                         f"despawn the other's entity")
            tags.add(st["tag"])
            if not st["template"].endswith(".ent"):
                sys.exit(f"{w} state {st['tag']!r} template {st['template']!r} is not a .ent")
            for c in st["when"]:
                if c["fact"] not in item["watch"]:
                    sys.exit(f"{w} state {st['tag']!r} tests fact {c['fact']!r}, which is "
                             f"not in 'watch' - the state would only change on a reload")
                if "min" not in c and "max" not in c:
                    sys.exit(f"{w} state {st['tag']!r} condition on {c['fact']!r} has "
                             f"neither 'min' nor 'max'")
        if [s for s in item["states"] if not s["when"]][1:]:
            sys.exit(f"{w} has more than one state with an empty 'when'; only the last "
                     f"state may be the default")
        if item["states"] and not item["states"][-1]["when"]:
            pass                         # the default is last, as it must be
        elif any(not s["when"] for s in item["states"]):
            sys.exit(f"{w} has a default state that is not last; it would shadow every "
                     f"state after it")

    # Hides (D134). A wrong one strips a room Phantom Liberty needs, or never
    # restores it, so the window has to be closed at both ends and every fact real.
    for h, data in hide_table(glue):
        w = f"glue.json hide {h['id']!r}"
        if not h["watch"]:
            sys.exit(f"{w} watches no facts, so the room would never change")
        for c in h["when"]:
            if c["fact"] not in declared:
                sys.exit(f"{w} tests fact {c['fact']!r}, which facts.json does not declare")
            if c["fact"] not in h["watch"]:
                sys.exit(f"{w} tests fact {c['fact']!r}, which is not in 'watch'")
        if not any("max" in c for c in h["when"]):
            sys.exit(f"{w} has no 'max': the vanilla furniture would never come back")
        # D139: ArchiveXL deletes it all, so 'hide' may be empty; an empty scan is not.
        if not any(sec["hide"] or sec["delete"] for sec in data["sectors"]):
            sys.exit(f"{w} removes nothing in any sector - rerun tools/clinic_hide_scan.py")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(emit(glue, world, items), encoding="utf-8")
    blocked = [k for k in glue["blocked"] if not k.startswith("_")]
    print(f"glue: {len(glue['areas'])} area(s), {len(glue['shards'])} shard hook(s), "
          f"{len(glue.get('props', []))} fact-driven prop(s) in "
          f"{sum(len(i['states']) for i in glue.get('props', []))} state(s), "
          f"{sum(len(s['hide']) for _, d in hide_table(glue) for s in d['sectors'])} vanilla setup(s) hideable, "
          f"1 start gate on {glue['start']['prerequisite']!r}, "
          f"{len(blocked)} fact(s) still blocked on world content "
          f"-> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
