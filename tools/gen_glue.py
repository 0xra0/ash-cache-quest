        "    // cannot jump a sphere: the next sample is timed for how long the gap",
        "    // takes to close at 60 m/s, the rough ceiling for a vehicle here. Far",
        "    // away that is one sample every five seconds; on the doorstep it is",
        "    // four a second.",
        "    this.ScheduleWatch(ClampF(gap / 60.00, 0.25, 5.00));",
        "  }",
