        "    GameInstance.GetDelaySystem(this.GetGameInstance()).DelayCallback(cb, 2.00, false);",
        "  }",
        "}",
        "",
        "// The drawing itself. Codeware, because the engine has no way to take a placed",
        "// sector node back out of the world - which is why source/world.json carries the",
        "// case as a 'disabled' prop: that entry is the measured pose, not a node.",
        "//",
        "// persistSpawn false, exactly as the echo fragments do it: the save then never",
        "// carries a case in the wrong state, and Resync redraws it from the facts on the",
        "// next load. IsPopulated counts registered entities rather than streamed-in ones,",
        "// so a second call while one is already up is a no-op.",
        "@if(ModuleExists(\"Codeware\"))",
