#!/usr/bin/env python3
"""Allocate a stable voicetag CRUID for every character with a body in a scene.

A voicetag is the id the engine uses to say "this actor, in any scene". It is
NOT the line id and NOT the character record - it is a third namespace, and it is
the only key the lipsync map has:

    .scene   scnActorDef.voicetagId.id          <- who is speaking
    .lipmap  sceneEntries[i].actorVoiceTags[j]  <- same number
             sceneEntries[i].animSets[j]        -> that actor's mouth animation

Verified, not guessed. Johnny's voicetag is 1103967280742240508 in vanilla's
mq029_01a_garage.scene, and the same number appears in base\\localization\\
en-us.lipmap against base\\localization\\en-us\\lipsync\\base\\quest\\
minor_quests\\mq029\\scenes\\mq029_01a_garage\\johnny.anims. The Kidnap mod
reuses that exact number to give Johnny custom lipsync, which also proves a
voicetag is global to a character rather than local to a scene.

Reserved block for Ash Cache: 7731600000000000000-7731600000000000099.
Same 77316 project marker as the LocKey and subtitle blocks, one digit apart
from subtitles (77315) so the two cannot be confused in a log. Well clear of
vanilla (~1.1e18) and below 2^63.

The player is deliberately NOT allocated one. V keeps voicetagId 0: the game
ships no lipsync animset for the player in any scene (0 of 5688 files under
base\\localization\\en-us\\lipsync\\ name one), because V is normally seen from
the inside. Giving V a tag would create a key nothing can ever answer.

CORRECTED 2026-09-15 (OI-21): this file still allocates V nothing, but the
scene no longer writes 0 for V. gen_scene.py writes V's own vanilla voicetag
1103967280742240864, which every census scene giving the player a lipsync
set carries. 0 is not "no key"; it is a key no scene with dialogue uses.
"""
import json
import pathlib
import sys

BLOCK_START = 7731600000000000000
BLOCK_END = 7731600000000000099

ROOT = pathlib.Path(__file__).resolve().parent.parent
ALLOC = ROOT / "source" / "voicetags.json"


def main():
    chars = json.loads((ROOT / "source" / "characters.json").read_text(encoding="utf-8"))
    ids = [c["id"] for c in chars["characters"]]

    alloc = {}
    if ALLOC.exists():
        alloc = json.loads(ALLOC.read_text(encoding="utf-8"))
        alloc.pop("_comment", None)

    used = {int(v) for v in alloc.values()}
    nxt = BLOCK_START
    added = []
    for cid in ids:
        if cid in alloc:
            continue
        while nxt in used:
            nxt += 1
        if nxt > BLOCK_END:
            sys.exit(f"voicetag block {BLOCK_START}-{BLOCK_END} exhausted")
        # String, like subtitle ids: these exceed 2^53 and any consumer that
        # parsed the file as JSON numbers would round them.
        alloc[cid] = str(nxt)
        used.add(nxt)
        added.append((cid, nxt))
        nxt += 1

    orphans = [k for k in alloc if k not in ids]

    out = {"_comment": f"Generated by tools/alloc_voicetags.py. "
                       f"Block {BLOCK_START}-{BLOCK_END}. "
                       "Append-only - a renumbered voicetag unbinds that "
                       "character's lipsync from every scene at once."}
    out.update({k: alloc[k] for k in sorted(alloc, key=lambda x: int(alloc[x]))})
    ALLOC.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"allocated {len(added)} new, {len(alloc)} total voicetag(s)")
    for cid, n in added:
        print(f"  +{n}  {cid}")
    if orphans:
        print(f"WARNING: {len(orphans)} allocated voicetag(s) no longer name a "
              f"character (kept, never reuse the number): {orphans}")


if __name__ == "__main__":
    main()
