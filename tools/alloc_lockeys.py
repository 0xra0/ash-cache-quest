#!/usr/bin/env python3
"""Allocate stable LocKey numbers for every symbolic string id.

LocKeys are a flat global namespace shared with vanilla and every other installed
mod, so they are allocated ONCE from a reserved block and then never renumbered -
a shifted LocKey silently repoints existing text. The allocation lives in
source/lockeys.json and is committed; this script only ever appends.

Reserved block for Ash Cache: 77315000-77315999.
Chosen to sit clear of vanilla (6-digit) and of Aldecaldos High Stakes (53848361+),
the only mod-authored range verified locally.
"""
import json
import pathlib
import sys

BLOCK_START = 77315000
BLOCK_END = 77315999

ROOT = pathlib.Path(__file__).resolve().parent.parent
STRINGS = ROOT / "source" / "strings.json"
LOCKEYS = ROOT / "source" / "lockeys.json"


def main():
    strings = json.loads(STRINGS.read_text(encoding="utf-8"))
    ids = [k for k in strings if not k.startswith("_")]

    alloc = {}
    if LOCKEYS.exists():
        alloc = json.loads(LOCKEYS.read_text(encoding="utf-8"))
        alloc.pop("_comment", None)

    used = set(alloc.values())
    nxt = BLOCK_START
    added = []
    for sid in ids:
        if sid in alloc:
            continue
        while nxt in used:
            nxt += 1
        if nxt > BLOCK_END:
            sys.exit(f"LocKey block {BLOCK_START}-{BLOCK_END} exhausted")
        alloc[sid] = nxt
        used.add(nxt)
        added.append((sid, nxt))
        nxt += 1

    orphans = [k for k in alloc if k not in ids]

    out = {"_comment": f"Generated by tools/alloc_lockeys.py. Block {BLOCK_START}-{BLOCK_END}. "
                       "Append-only - never renumber an existing entry."}
    out.update({k: alloc[k] for k in sorted(alloc, key=lambda x: alloc[x])})
    LOCKEYS.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"allocated {len(added)} new, {len(alloc)} total")
    for sid, n in added:
        print(f"  +{n}  {sid}")
    if orphans:
        print(f"WARNING: {len(orphans)} allocated ids no longer in strings.json "
              f"(kept, never reuse the number): {orphans}")


if __name__ == "__main__":
    main()
